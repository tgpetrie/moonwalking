import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const frontendRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const tokenPath = path.join(frontendRoot, "src/design-system/tokens.json");
const lockPath = path.join(frontendRoot, "src/design-system/.tokens-build.lock");

export function collectTokens(node, pathParts = [], result = new Map(), inheritedType) {
  if (!node || typeof node !== "object" || Array.isArray(node)) return result;
  const type = node.$type || inheritedType;
  if (Object.hasOwn(node, "$value")) {
    result.set(pathParts.join("."), { ...node, $type: type });
    return result;
  }
  for (const [key, value] of Object.entries(node)) {
    if (!key.startsWith("$")) collectTokens(value, [...pathParts, key], result, type);
  }
  return result;
}

function aliasPath(value) {
  return typeof value === "string" ? value.match(/^\{(.+)\}$/)?.[1] : undefined;
}

export function resolveToken(name, tokens, chain = []) {
  if (chain.includes(name)) throw new Error(`Circular token alias: ${[...chain, name].join(" -> ")}`);
  const token = tokens.get(name);
  if (!token) throw new Error(`Missing token: ${name}`);
  const alias = aliasPath(token.$value);
  if (!alias) return token;
  const resolved = resolveToken(alias, tokens, [...chain, name]);
  if (token.$type !== resolved.$type) throw new Error(`Alias type mismatch: ${name}`);
  return resolved;
}

function cssLiteral(value, type) {
  switch (type) {
    case "color": {
      if (value.colorSpace !== "srgb" || !Array.isArray(value.components) || value.components.length !== 3 ||
          value.components.some((part) => !Number.isFinite(part) || part < 0 || part > 1) ||
          !Number.isFinite(value.alpha) || value.alpha < 0 || value.alpha > 1) {
        throw new Error("Invalid sRGB color token");
      }
      return `rgba(${value.components.map((part) => Math.round(part * 255)).join(", ")}, ${value.alpha})`;
    }
    case "dimension":
    case "duration":
      if (!Number.isFinite(value.value) || !(type === "dimension" ? ["px", "rem"] : ["ms", "s"]).includes(value.unit)) {
        throw new Error(`Invalid ${type} token`);
      }
      return `${value.value}${value.unit}`;
    case "fontFamily":
      if (!Array.isArray(value) || value.some((font) => typeof font !== "string")) throw new Error("Invalid font family");
      return value.map((font) => font.includes(" ") ? JSON.stringify(font) : font).join(", ");
    case "cubicBezier":
      if (!Array.isArray(value) || value.length !== 4 || value.some((part) => !Number.isFinite(part))) throw new Error("Invalid easing");
      return `cubic-bezier(${value.join(", ")})`;
    case "shadow":
      return `${["offsetX", "offsetY", "blur", "spread"].map((key) => cssLiteral(value[key], "dimension")).join(" ")} ${cssLiteral(value.color, "color")}`;
    case "number":
      if (!Number.isFinite(value)) throw new Error("Invalid numeric token");
      return String(value);
    default:
      throw new Error(`Unsupported token type: ${type}`);
  }
}

export function validateTokens(tokens) {
  const variables = new Set();
  for (const [name, token] of tokens) {
    const resolved = resolveToken(name, tokens);
    cssLiteral(resolved.$value, resolved.$type);
    const variable = token.$extensions?.["com.moonwalking.cssVariable"];
    if (variable && variables.has(variable)) throw new Error(`Duplicate CSS variable: ${variable}`);
    if (variable) variables.add(variable);
  }
}

export function renderTokenCss(source) {
  const tokens = collectTokens(source);
  validateTokens(tokens);
  const lines = [
    "/* AUTO-GENERATED by scripts/designTokens.mjs from src/design-system/tokens.json.",
    "   Edit the JSON source, then run `npm run tokens:build`. */",
    ":root {",
  ];
  for (const [name, token] of tokens) {
    const extensions = token.$extensions || {};
    const variable = extensions["com.moonwalking.cssVariable"];
    if (!variable) continue;
    const alias = aliasPath(token.$value);
    const targetVariable = alias && tokens.get(alias)?.$extensions?.["com.moonwalking.cssVariable"];
    if (alias && !targetVariable) throw new Error(`Alias target lacks CSS mapping: ${alias}`);
    const value = alias ? `var(${targetVariable})` : cssLiteral(token.$value, token.$type);
    lines.push(`  ${variable}: ${value}${extensions["com.moonwalking.cssUnit"] || ""}; /* ${name} */`);
  }
  lines.push("}", "");
  return lines.join("\n");
}

function collectionFor(name) {
  if (name.startsWith("color.primitive.")) return "Primitives";
  if (name.startsWith("color.semantic.")) return "Semantic";
  return { radius: "Shape", control: "Layout", spacing: "Spacing", density: "Spacing", layout: "Layout", typography: "Typography", motion: "Motion", shadow: "Effects", zIndex: "Layout", breakpoint: "Breakpoints" }[name.split(".")[0]];
}

export function renderFigmaManifest(source) {
  const tokens = collectTokens(source);
  validateTokens(tokens);
  const variables = [];
  const styleTokens = [];
  for (const [name, token] of tokens) {
    const resolved = resolveToken(name, tokens);
    const value = resolved.$value;
    const type = resolved.$type;
    const extensions = token.$extensions || {};
    const variable = extensions["com.moonwalking.cssVariable"];
    const entry = {
      name: name.replaceAll(".", "/"),
      collection: collectionFor(name),
      mode: name.startsWith("color.semantic.") ? "Midnight" : "Value",
      codeSyntax: variable ? { WEB: `var(${variable})` } : undefined,
      scopes: name.startsWith("color.primitive.") ? [] : (extensions["com.moonwalking.figmaScope"] ||
        (name.startsWith("spacing.") || name.startsWith("density.") || name.startsWith("layout.") ? ["GAP"] :
          name.startsWith("typography.size.") ? ["FONT_SIZE"] :
            name.startsWith("typography.family.") ? ["FONT_FAMILY"] :
              name.startsWith("typography.weight.") ? ["FONT_WEIGHT"] : [])),
      alias: aliasPath(token.$value)?.replaceAll(".", "/"),
    };
    if (type === "shadow" || type === "cubicBezier") {
      styleTokens.push({ ...entry, type, value });
      continue;
    }
    if (type === "color") {
      entry.resolvedType = "COLOR";
      entry.value = { r: value.components[0], g: value.components[1], b: value.components[2], a: value.alpha };
    } else if (type === "fontFamily") {
      entry.resolvedType = "STRING";
      entry.value = value[0];
    } else {
      entry.resolvedType = "FLOAT";
      entry.value = typeof value === "number" ? value : value.value * (value.unit === "rem" ? 16 : value.unit === "s" ? 1000 : 1);
      entry.sourceUnit = extensions["com.moonwalking.cssUnit"] || value.unit;
      if (extensions["com.moonwalking.figmaUnit"] === "PERCENT") {
        entry.value *= 100;
        entry.figmaUnit = "PERCENT";
      }
    }
    variables.push(entry);
  }
  return JSON.stringify({
    format: "moonwalking-figma-manifest-v1",
    description: "Adapter manifest for Figma Plugin API; not a native Figma import file. Rem conversion uses a 16px root.",
    variables,
    styleTokens,
  }, null, 2) + "\n";
}

function publishOutputs(outputs, sourceSnapshot) {
  const lock = fs.openSync(lockPath, "wx");
  fs.writeFileSync(lock, String(process.pid));
  const staged = outputs.map(([relativePath, expected]) => {
    const output = path.join(frontendRoot, relativePath);
    return { output, expected, temporary: `${output}.tmp-${process.pid}`, previous: fs.existsSync(output) ? fs.readFileSync(output) : undefined };
  });
  let published = false;
  try {
    for (const entry of staged) fs.writeFileSync(entry.temporary, entry.expected);
    if (fs.readFileSync(tokenPath, "utf8") !== sourceSnapshot) throw new Error("Token source changed during generation. Run tokens:build again.");
    published = true;
    for (const entry of staged) fs.renameSync(entry.temporary, entry.output);
  } catch (error) {
    if (published) {
      for (const entry of staged) {
        if (entry.previous !== undefined) fs.writeFileSync(entry.output, entry.previous);
        else fs.rmSync(entry.output, { force: true });
      }
    }
    throw error;
  } finally {
    for (const entry of staged) fs.rmSync(entry.temporary, { force: true });
    fs.closeSync(lock);
    fs.rmSync(lockPath);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  // A process killed between publications leaves this marker; checks and builds
  // must refuse that partial generation until it has been regenerated.
  if (fs.existsSync(lockPath)) throw new Error("Token generation is running or was interrupted. Confirm no tokens:build process is running, remove src/design-system/.tokens-build.lock, then regenerate.");
  const sourceSnapshot = fs.readFileSync(tokenPath, "utf8");
  const source = JSON.parse(sourceSnapshot);
  const mode = process.argv[2] || "build";
  if (!["build", "check"].includes(mode)) throw new Error(`Unknown mode: ${mode}`);
  const outputs = [
    ["src/styles/design-tokens.css", renderTokenCss(source)],
    ["src/design-system/tokens.figma.json", renderFigmaManifest(source)],
  ];
  if (mode === "build") publishOutputs(outputs, sourceSnapshot);
  else for (const [relativePath, expected] of outputs) {
    const output = path.join(frontendRoot, relativePath);
    if (!fs.existsSync(output) || fs.readFileSync(output, "utf8").replaceAll("\r\n", "\n") !== expected) {
      throw new Error(`${relativePath} is stale. Run npm run tokens:build.`);
    }
  }
  console.log(mode === "build" ? "Generated CSS tokens and Figma manifest." : "CSS tokens and Figma manifest are in sync.");
}
