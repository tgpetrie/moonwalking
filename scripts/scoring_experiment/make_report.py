"""Render the numeric tables of docs/research/SCORING_BASELINE_RESULTS.md from the result JSON files.

Interpretation text is written by hand in the same document; this script only produces tables.
    python scripts/scoring_experiment/make_report.py > tables.md
"""
from __future__ import annotations

import json
from pathlib import Path

OUT = Path(__file__).resolve().parents[2] / "docs" / "research" / "results" / "scoring_baseline"


def load(name):
    return json.loads((OUT / name).read_text(encoding="utf-8"))


def n(x, d=3, pct=False):
    if x is None:
        return "n/a"
    return f"{x:+.{d}f}" + ("%" if pct else "")


def ci(e, d=3):
    return f"{n(e.get('mean'), d)} [{n(e.get('lo'), d)}, {n(e.get('hi'), d)}]"


def main():
    disc, test = load("results_discovery_base.json"), load("results_test_base.json")
    sig = load("recorded_signals.json")
    P = []
    out = P.append
    out("## Tables (generated by `make_report.py`; do not edit by hand)\n")
    out(f"Input manifest SHA-256: `{test['input']}`. Code commit for the test run: `{test['code_commit']}`. "
        f"Config hash: `{test['config_hash']}`.\n")
    b = test["build"]
    out("### Eligibility and exclusions (counts of coin-days; categories overlap)\n")
    out("| Reason | Coin-days |\n|---|---:|")
    labels = {"decision_day_candle_missing": "no candle on the day (not yet listed, delisted, or a gap)",
              "history_under_min": "has a candle but under 90 days of history",
              "window_gaps_over_limit": "enough history but fewer than 80 usable days in the 90-day window",
              "core_feature_missing": "a core input is missing",
              "pegged_or_near_zero_volatility": "30-day volatility below 0.3% per day (pegged)",
              "benchmark_row_BTC-USD": "BTC-USD benchmark row",
              "eligible_coin_days": "**eligible for scoring**"}
    for k, v in b["exclusions"].items():
        out(f"| {labels.get(k, k)} | {v:,} |")
    out(f"\nDays with fewer than 20 eligible coins dropped: {b['rows_dropped_for_small_cross_section']:,} rows. "
        f"Funding-candidate rows in the eligible set: {b['funding_rows']:,}.\n")

    out("### Primary tests: rank IC of the score against the label (97.5% week-block interval)\n")
    out("| Horizon | Phase | Blocks (weeks) | Mean IC [interval] | Frozen sign | Verdict |\n|---|---|---:|---|---:|---|")
    for h in ("h1", "h7"):
        for name, r in (("discovery", disc), ("test", test)):
            p = r["evaluation"]["primary"][h]
            mb = p["estimate"]["moving_block"]
            out(f"| {h[1:]} day | {name} | {p['estimate']['n_blocks']} | {ci(p['estimate'])} | [{n(mb['lo'])}, {n(mb['hi'])}] | "
                f"{p['weekday_phases_excluding_zero']} | {p['frozen_sign']:+d} | "
                f"{p['verdict'] if name == 'test' else '(sign frozen here)'} |")
    out("")
    out("### Same-row comparison (all eligible coins): IC and model minus comparator\n")
    out("| Horizon | Phase | Predictor | Mean IC [interval] | Model minus predictor [interval] |\n|---|---|---|---|---|")
    for h in ("h1", "h7"):
        for name, r in (("discovery", disc), ("test", test)):
            s = r["evaluation"][h]["all"]
            out(f"| {h[1:]}d | {name} | model | {ci(s['model'])} | |")
            for k, lab in (("reversal_neg_r1", "reversal (-r1)"), ("momentum_res7", "residual momentum (res7)"),
                           ("extension_neg_ext30", "extension (-ext30)")):
                out(f"| | | {lab} | {ci(s[k])} | {ci(s[k]['model_minus_this_weekly_ic'])} |")
            out(f"| | | shuffled-label null | {ci(s['shuffled_label_null'])} | |")
    out("")
    out("### By universe subset (test phase, model IC)\n")
    out("| Horizon | All eligible | Funding-candidate subset | Excluding thin coins |\n|---|---|---|---|")
    for h in ("h1", "h7"):
        s = test["evaluation"][h]
        out(f"| {h[1:]}d | {ci(s['all']['model'])} | {ci(s['funding_candidates']['model'])} | {ci(s['excluding_thin']['model'])} |")
    out("")
    for h in ("h1", "h7"):
        out(f"### Score buckets, {h[1:]}-day label, test phase (mean over days, week-block interval)\n")
        out("| Score | Rows | Scaled residual [interval] | Raw return % [interval] |\n|---|---:|---|---|")
        for d in test["evaluation"][h]["deciles"]:
            out(f"| {d['bucket']} | {d['n_rows']:,} | {n(d['mean_scaled_residual'])} [{n(d['lo'])}, {n(d['hi'])}] | "
                f"{n(d['mean_btc_residual_log_return_pct'], 2)} [{n(d['residual_lo_pct'], 2)}, {n(d['residual_hi_pct'], 2)}] | "
                f"{n(d['mean_raw_return_pct'], 2)} [{n(d['raw_lo_pct'], 2)}, {n(d['raw_hi_pct'], 2)}] |")
        sp = test["evaluation"][h]["top_decile_minus_bottom_decile_scaled_residual"]
        out(f"\nTop decile minus bottom decile (scaled residual): {ci(sp)}.\n")
    q = test["evaluation"]["h7"]["top_quintile_weekly_excess"]
    d_ = disc["evaluation"]["h7"]["top_quintile_weekly_excess"]
    out("### Long-only top quintile versus the equal-weight eligible universe, 7-day horizon, weekly (percentage points per week)\n")
    out("| | Discovery | Test |\n|---|---|---|")
    out(f"| Gross excess | {ci(d_['gross_excess_pct'], 2)} | {ci(q['gross_excess_pct'], 2)} |")
    for c in (0.2, 0.5, 0.9, 1.2):
        k = f"net_excess_pct_cost_{c}"
        out(f"| After {c}% round-trip cost (assumed) | {ci(d_[k], 2)} | {ci(q[k], 2)} |")
    out("\nThe top quintile is rebalanced fully each week; the benchmark is cost-free. Costs are scenarios, not measured.\n")

    out("### Test-phase breakdowns of model IC\n")
    out("| Horizon | Cut | Group | Blocks | Mean IC [interval] | Interpretable |\n|---|---|---|---:|---|---|")
    for h in ("h1", "h7"):
        s = test["evaluation"][h]
        for k, e in s["by_btc_30d_regime"].items():
            out(f"| {h[1:]}d | BTC 30-day trend | {k} | {e['n_blocks']} | {ci(e)} | {'yes' if e['interpretable'] else 'no (under 15 blocks)'} |")
        for k, e in s["by_calendar_year"].items():
            out(f"| {h[1:]}d | calendar year | {k} | {e['n_blocks']} | {ci(e)} | |")
        for k, e in s["by_evidence_coverage"].items():
            out(f"| {h[1:]}d | evidence coverage | {k} (rows {e['share_of_rows']:.0%}) | {e['n_blocks']} | {ci(e)} | |")
    out("")
    out("### Risk rank (same-day trailing-volatility percentile) versus the forward absolute residual move, test phase\n")
    out("| Horizon | Mean IC [interval] | Thin-coin mean absolute move over non-thin |\n|---|---|---:|")
    for h, e in test["evaluation"]["risk_rank_vs_forward_absolute_residual_move"].items():
        out(f"| {h[1:]}d | {ci(e)} | {e['thin_over_nonthin_mean_abs_residual']:.2f} |")
    out("")
    out("### Drop-one factor group (test phase, model IC with the group removed)\n")
    out("| Group removed | 1-day IC [interval] | 7-day IC [interval] |\n|---|---|---|")
    for g, v in test["drop_one_factor_group"].items():
        out(f"| {g} | {ci(v['h1'])} | {ci(v['h7'])} |")
    out("")
    out("### Continuation versus exhaustion events, daily panel (percentage points of BTC-residual return)\n")
    out("Each cell: event minus comparator, mean [97.5% interval over weeks]. Frozen sign from discovery.\n")
    out("| Event | Phase | Events (matched) | Coins / weeks | Horizon | vs clean same-coin controls | vs same-day universe | Frozen sign | Status (test) |\n|---|---|---|---|---|---|---|---:|---|")
    for cls in ("exhaustion", "continuation", "capitulation", "downside_continuation"):
        for name, r in (("discovery", disc), ("test", test)):
            e = r["evaluation"]["events"][cls]
            for h in (1, 7):
                out(f"| {cls} | {name} | {e['events_in_period']:,} ({e['events_matched']:,}) | "
                    f"{e.get('distinct_coins', 0)} / {e.get('distinct_weeks', 0)} | {h}d | "
                    f"{ci(e.get(f'h{h}_vs_clean_controls_pp', {}), 2)} | {ci(e.get(f'h{h}_vs_same_day_universe_pp', {}), 2)} | "
                    f"{e.get(f'h{h}_frozen_sign', 0):+d} | {e.get(f'h{h}_status', '-') if name == 'test' else '-'} |")
    out("")
    out("### Recorded production signals (short horizon, exploratory, selected population)\n")
    out("Excess over clean matched same-coin non-signal hours; ATR units for r4/r12/r24; net R after an assumed 0.2% cost.\n")
    out("| Read | Matched / weeks | Outcome | Signal | Control | Excess [interval] | First half | Second half |\n|---|---|---|---:|---:|---|---|---|")
    for name, e in sig["reads"].items():
        for k in ("netR21", "r4", "r12", "r24"):
            if k in e:
                x = e[k]
                out(f"| {name} | {e['matched']:,} / {e['distinct_weeks']} | {k} | {n(x['signal_mean'])} | {n(x['control_mean'])} | "
                    f"{ci(x['excess'])} | {n(x['first_half']['mean'])} | {n(x['second_half']['mean'])} |")
    out("\nGraded 15- and 60-minute returns (within-signal only; percent, week-block interval):\n")
    out("| Population | Rows | 15 minutes | 60 minutes |\n|---|---:|---|---|")
    for name, e in sig["short_horizon_within_signal"].items():
        out(f"| {name} | {e['n']:,} | {ci(e['return_15m_pct'], 3)} | {ci(e['return_60m_pct'], 3)} |")
    out("")
    out("### Sample scores (latest decision date)\n")
    out("Ordinal percentile ranks among that day's eligible coins; not probabilities. Drivers are the three largest signed "
        "contributions to the 7-day prediction (rank-normal feature times coefficient).\n")
    out("| Coin | 1-day score | 7-day score | Largest 7-day drivers | Evidence coverage | Risk rank | Daily vol | Flags |\n|---|---:|---:|---|---:|---:|---:|---|")
    for r in test["sample_scores"]:
        drivers = ", ".join(f"{k} {v:+.2f}" for k, v in r["top_drivers_7d"].items())
        out(f"| {r['product']} | {r['score_1d']} | {r['score_7d']} | {drivers} | {r['evidence_coverage']} | "
            f"{r['risk_rank_pct']} | {r['vol30_daily_pct']}% | {', '.join(r['flags']) or '-'} |")
    out(f"\nDate: {test['sample_scores'][0]['date']}; eligible coins that day: {test['sample_scores'][0]['eligible_coins_that_day']}.\n")
    print("\n".join(P))


if __name__ == "__main__":
    main()
