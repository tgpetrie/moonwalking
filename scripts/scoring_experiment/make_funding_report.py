"""Render the numeric tables of the funding comparison from results_{discovery,test}_funding.json.

    python scripts/scoring_experiment/make_funding_report.py > tables_funding.md
"""
from __future__ import annotations

import json
from pathlib import Path

OUT = Path(__file__).resolve().parents[2] / "docs" / "research" / "results" / "funding_comparison"


def n(x, d=3):
    return "n/a" if x is None else f"{x:+.{d}f}"


def ci(e, d=3):
    if not e or e.get("mean") is None:
        return "n/a"
    return f"{n(e['mean'], d)} [{n(e['lo'], d)}, {n(e['hi'], d)}]"


def main():
    disc = json.loads((OUT / "results_discovery_funding.json").read_text(encoding="utf-8"))
    test = json.loads((OUT / "results_test_funding.json").read_text(encoding="utf-8"))
    P = []
    out = P.append
    out("## Tables (generated by `make_funding_report.py`; do not edit by hand)\n")
    out(f"Code commit for the test run: `{test['code_commit']}`. Configuration hash: `{test['config_hash']}`.\n")
    out("### Matched rows (identical for every model)\n")
    out("| | Discovery | Test |\n|---|---:|---:|")
    for k, lab in (("rows_with_valid_funding_feature", "Rows with a valid funding feature (all dates)"),
                   ("rows_after_20_coin_day_rule", "After the 20-coin-per-day rule (all dates)"),
                   ("products_with_matched_rows", "Products with matched rows"),
                   ("first_date", "First matched date"), ("last_date", "Last matched date"),
                   ("rows_in_period", "Matched rows in the phase"), ("weeks_in_period", "Weeks in the phase"),
                   ("mean_coins_per_day_in_period", "Mean coins per day in the phase"),
                   ("min_coins_per_day_in_period", "Fewest coins on a day in the phase"),
                   ("baseline_eligible_rows_for_approved_products", "Baseline-eligible rows of the 127 approved products")):
        a, b = disc["matched"][k], test["matched"][k]
        fmt = (lambda v: f"{v:,.1f}") if k == "mean_coins_per_day_in_period" else (lambda v: f"{v:,}" if isinstance(v, int) else str(v))
        out(f"| {lab} | {fmt(a)} | {fmt(b)} |")
    out(f"\nFirst model fit (month): 1 day {test['walk_forward_first_fit']['h1']}, 7 day {test['walk_forward_first_fit']['h7']}.\n")
    out("### Primary tests: incremental rank IC, M1 (baseline + funding) minus M0-matched, identical rows, primary one-day lag\n")
    out("| Horizon | Phase | Mean IC M0-matched | Mean IC M1 | Difference [97.5% week-block interval] | 4-week moving-block interval | Verdict |\n|---|---|---:|---:|---|---|---|")
    for h in ("h1", "h7"):
        for name, r in (("discovery", disc), ("test", test)):
            e = r["variants"]["primary_lag_1d"][h]["all_matched"]["incremental_ic_m1_minus_m0"]
            mb = e["moving_block"]
            v = r["variants"]["primary_lag_1d"][h].get("verdict", "(sign basis only)")
            out(f"| {h[1:]} day | {name} | {n(e['mean_ic_m0'])} | {n(e['mean_ic_m1'])} | {ci(e)} | [{n(mb['lo'])}, {n(mb['hi'])}] | {v} |")
    out("")
    out("Test-phase verdict inputs: discovery difference positive? coefficient sign the same? Minimum effect of interest +0.02.\n")
    out("| Horizon | Discovery difference | Funding coefficient (mean of monthly fits) discovery | test | Same sign |\n|---|---:|---:|---:|---|")
    for h in ("h1", "h7"):
        t = test["variants"]["primary_lag_1d"][h]
        out(f"| {h[1:]}d | {n(t['discovery_difference_mean'])} | {n(disc['fz_coefficient'][h]['mean_coef'], 4)} | "
            f"{n(test['fz_coefficient'][h]['mean_coef'], 4)} | {t['coefficient_sign_same_in_discovery_and_test']} |")
    out("")
    out("### Rank IC of each model against the label on the matched rows (mean [97.5% interval])\n")
    out("| Horizon | Phase | M0-matched | M1 | Baseline model fitted on all eligible coins (M0-full) | Funding alone (z) | Funding level alone | Residualised funding (beyond M0-matched) |\n|---|---|---|---|---|---|---|---|")
    for h in ("h1", "h7"):
        for name, r in (("discovery", disc), ("test", test)):
            e = r["variants"]["primary_lag_1d"][h]["all_matched"]
            out(f"| {h[1:]}d | {name} | {ci(e['m0_matched'])} | {ci(e['m1'])} | {ci(e['m0_full_universe_model_on_matched_rows'])} | "
                f"{ci(e['funding_alone_rank_normal_z'])} | {ci(e['funding_level_alone'])} | {ci(e['residualised_incremental_ic'])} |")
    out("")
    out("### Incremental IC (M1 minus M0-matched), test phase, by weekday of decision (labels never overlap within a weekday)\n")
    out("| Horizon | Mon | Tue | Wed | Thu | Fri | Sat | Sun |\n|---|---|---|---|---|---|---|---|")
    for h in ("h1", "h7"):
        ph = test["variants"]["primary_lag_1d"][h]["all_matched"]["weekday_phases_incremental"]
        out(f"| {h[1:]}d | " + " | ".join(ci(ph[k]) for k in ph) + " |")
    out("")
    out("### Incremental IC by cut and sensitivity (test phase, difference M1 minus M0-matched)\n")
    out("| Horizon | Cut / variant | Difference [interval] | M0-matched IC | M1 IC |\n|---|---|---|---|---|")
    for h in ("h1", "h7"):
        for cut, e in test["variants"]["primary_lag_1d"][h].items():
            if isinstance(e, dict) and "incremental_ic_m1_minus_m0" in e:
                out(f"| {h[1:]}d | primary lag, {cut.replace('_', ' ')} | {ci(e['incremental_ic_m1_minus_m0'])} | {n(e['incremental_ic_m1_minus_m0']['mean_ic_m0'])} | {n(e['incremental_ic_m1_minus_m0']['mean_ic_m1'])} |")
        e = test["variants"]["same_day_window"][h]["all_matched"]
        out(f"| {h[1:]}d | same-day window (less conservative) | {ci(e['incremental_ic_m1_minus_m0'])} | {n(e['incremental_ic_m1_minus_m0']['mean_ic_m0'])} | {n(e['incremental_ic_m1_minus_m0']['mean_ic_m1'])} |")
    out("")
    out("### Incremental IC by BTC 30-day regime and calendar year (test phase)\n")
    out("| Horizon | Group | Blocks | Difference [interval] | Interpretable |\n|---|---|---:|---|---|")
    for h in ("h1", "h7"):
        e = test["variants"]["primary_lag_1d"][h]["all_matched"]
        for k, v in e["by_btc_30d_regime"].items():
            out(f"| {h[1:]}d | BTC {k} | {v['n_blocks']} | {ci(v)} | {'yes' if v['interpretable'] else 'no (under 15 blocks)'} |")
        for k, v in e["by_calendar_year"].items():
            out(f"| {h[1:]}d | {k} | {v['n_blocks']} | {ci(v)} | |")
    out("")
    out("### Extreme funding events (rolling z at least +2 / at most -2; percentage points of BTC-residual return)\n")
    out("| Event | Phase | Events (matched) | Coins / weeks | Horizon | vs clean same-coin controls | vs same-day matched universe | Frozen sign | Status (test) |\n|---|---|---|---|---|---|---|---:|---|")
    for cls in ("high_funding", "low_funding"):
        for name, r in (("discovery", disc), ("test", test)):
            e = r["events"][cls]
            for h in (1, 7):
                sg = e.get(f"h{h}_frozen_sign")
                out(f"| {cls.replace('_', ' ')} | {name} | {e['events_in_period']:,} ({e['events_matched']:,}) | "
                    f"{e.get('distinct_coins', 0)} / {e.get('distinct_weeks', 0)} | {h}d | {ci(e.get(f'h{h}_vs_clean_controls_pp'), 2)} | "
                    f"{ci(e.get(f'h{h}_vs_same_day_universe_pp'), 2)} | {0 if sg is None else sg:+d} | {e.get(f'h{h}_status', '-') if name == 'test' else '-'} |")
    out("")
    out("### Per-product funding coverage and matched rows (test-phase run; all dates)\n")
    out("| Product | First funding | Last funding | Rows | Missing hours (est.) | Duplicates | Valid daily means | Matched rows |\n|---|---|---|---:|---:|---:|---:|---:|")
    for pid, v in sorted(test["per_product"].items()):
        out(f"| {pid} | {(v.get('first_utc') or 'none')[:10]} | {(v.get('last_utc') or 'none')[:10]} | {v.get('raw_rows', 0):,} | "
            f"{v.get('missing_hours_estimate', 'n/a')} | {v.get('duplicates_identical', 0)} | {v.get('days_with_valid_mean', 0)} | {v.get('matched_rows', 0):,} |")
    out("")
    if "sample_scores" in test:
        out("### Sample scores on the latest decision date (ordinal percentile ranks among matched coins; not probabilities)\n")
        out("| Coin | Rolling funding z | Daily mean hourly funding (%) | 1-day M0 | 1-day M1 | 7-day M0 | 7-day M1 | Funding contribution (7-day) |\n|---|---:|---:|---:|---:|---:|---:|---:|")
        for r in test["sample_scores"]:
            out(f"| {r['product']} | {r['fz_raw_rolling_z']:+.2f} | {r['daily_mean_hourly_funding_pct']:+.5f} | {r['score_1d_m0']} | {r['score_1d_m1']} | "
                f"{r['score_7d_m0']} | {r['score_7d_m1']} | {r['funding_contribution_7d']} |")
        out(f"\nDate: {test['sample_scores'][0]['date']}; matched coins that day: {test['sample_scores'][0]['matched_coins_that_day']}.\n")
    print("\n".join(P))


if __name__ == "__main__":
    main()
